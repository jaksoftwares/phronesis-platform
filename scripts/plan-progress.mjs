#!/usr/bin/env node
// Generates docs/plan/PROGRESS.md and docs/plan/progress.json from docs/plan/implementation-plan.md.
//
// Usage:
//   node scripts/plan-progress.mjs           regenerate the report
//   node scripts/plan-progress.mjs --check   exit 1 if the committed report is out of date (used in CI)
//
// Work-item conventions in implementation-plan.md:
//   - [ ] P5.3 Text            not started
//   - [ ] P5.3 Text <!-- wip -->               in progress
//   - [ ] P5.3 Text <!-- blocked: reason -->   blocked
//   - [x] P5.3 Text            done (Definition of Done met and demonstrated on staging)
// A phase counts as "exited" when docs/plan/reviews/phase-NN.md exists.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const planDir = path.join(root, 'docs', 'plan');
const planFile = path.join(planDir, 'implementation-plan.md');
const decisionsFile = path.join(planDir, 'decisions-and-business-rules.md');
const outMd = path.join(planDir, 'PROGRESS.md');
const outJson = path.join(planDir, 'progress.json');

const MILESTONES = [
  { id: 'M1', name: 'Foundation on staging', phase: 1 },
  { id: 'M2', name: 'First verified teacher', phase: 3 },
  { id: 'M3', name: 'First published lesson', phase: 5 },
  { id: 'M4', name: 'First paid learner', phase: 7 },
  { id: 'M4b', name: 'First exam paper sold', phase: 7 },
  { id: 'M5', name: 'First live class', phase: 8 },
  { id: 'M6', name: 'Operational readiness', phase: 10 },
  { id: 'M7', name: 'Public launch', phase: 11 },
];

function parsePlan(text) {
  const phases = [];
  let current = null;
  for (const line of text.split(/\r?\n/)) {
    const ph = line.match(/^### Phase (\d+) — (.+?)(?: \((\d+(?:\.\d+)?) weeks?\))?(?: ·.*)?$/);
    if (ph) {
      current = { number: Number(ph[1]), title: ph[2].trim(), weeks: ph[3] ? Number(ph[3]) : 0, items: [] };
      phases.push(current);
      continue;
    }
    if (/^## /.test(line)) { current = null; continue; }
    const it = current && line.match(/^- \[( |x|X)\] (P\d+\.[A-Z0-9.]*[A-Z0-9]) (.*)$/);
    if (it) {
      const done = it[1].toLowerCase() === 'x';
      const blocked = it[3].match(/<!--\s*blocked:\s*(.*?)\s*-->/);
      const wip = /<!--\s*wip\s*-->/.test(it[3]);
      const title = it[3].replace(/<!--.*?-->/g, '').replace(/\*\*/g, '').trim();
      current.items.push({
        id: it[2], title, status: done ? 'done' : blocked ? 'blocked' : wip ? 'in-progress' : 'todo',
        blockedReason: blocked ? blocked[1] : undefined,
      });
    }
  }
  return phases.filter(p => p.items.length > 0);
}

function parseOpenDecisions(text) {
  const section = text.split(/^## 2\. Open decisions/m)[1]?.split(/^## /m)[0] ?? '';
  const rows = [];
  for (const line of section.split(/\r?\n/)) {
    const m = line.match(/^\| (O-\d+) \| (.+?) \| .+? \| (.+?) \|$/);
    if (m) {
      const gate = m[3].match(/Phase (\d+)/);
      rows.push({ id: m[1], question: m[2], gate: m[3].trim(), gatePhase: gate ? Number(gate[1]) : null });
    }
  }
  return rows;
}

const pct = (a, b) => (b === 0 ? 0 : Math.round((a / b) * 1000) / 10);
const bar = (p, width = 20) => '█'.repeat(Math.round((p / 100) * width)) + '░'.repeat(width - Math.round((p / 100) * width));
const short = (s, n = 90) => (s.length > n ? s.slice(0, n - 1) + '…' : s);

const phases = parsePlan(fs.readFileSync(planFile, 'utf8'));
const decisions = fs.existsSync(decisionsFile) ? parseOpenDecisions(fs.readFileSync(decisionsFile, 'utf8')) : [];

for (const p of phases) {
  const c = { done: 0, 'in-progress': 0, blocked: 0, todo: 0 };
  for (const i of p.items) c[i.status]++;
  p.counts = c;
  p.total = p.items.length;
  p.percent = pct(c.done, p.total);
  p.exited = fs.existsSync(path.join(planDir, 'reviews', `phase-${String(p.number).padStart(2, '0')}.md`));
  p.state = p.exited ? 'Exited' : c.done === p.total ? 'Awaiting exit review'
    : c.done + c['in-progress'] + c.blocked > 0 ? 'In progress' : 'Not started';
}

const scheduled = phases.filter(p => p.weeks > 0);
const totalWeeks = scheduled.reduce((s, p) => s + p.weeks, 0);
const overall = pct(scheduled.reduce((s, p) => s + p.weeks * (p.counts.done / p.total), 0), totalWeeks);
const all = phases.flatMap(p => p.items);
const totals = { done: 0, 'in-progress': 0, blocked: 0, todo: 0 };
for (const i of all) totals[i.status]++;
const currentPhase = scheduled.find(p => !p.exited) ?? null;
const milestones = MILESTONES.map(m => ({ ...m, reached: !!phases.find(p => p.number === m.phase && p.exited) }));
const decisionsDue = currentPhase ? decisions.filter(d => d.gatePhase !== null && d.gatePhase <= currentPhase.number + 1) : [];

const md = [];
md.push('# Delivery Progress');
md.push('');
md.push('> Generated by `node scripts/plan-progress.mjs` from [implementation-plan.md](implementation-plan.md). Do not edit by hand.');
md.push('');
md.push(`**Overall: ${overall}%** \`${bar(overall, 30)}\` (weighted by phase duration, ${totalWeeks} planned weeks)`);
md.push('');
md.push('| Current phase | Work items done | In progress | Blocked | Not started | Total |');
md.push('|---|---|---|---|---|---|');
md.push(`| ${currentPhase ? `P${currentPhase.number} — ${currentPhase.title}` : 'All phases exited'} | ${totals.done} | ${totals['in-progress']} | ${totals.blocked} | ${totals.todo} | ${all.length} |`);
md.push('');
md.push('## Phases');
md.push('');
md.push('| Phase | Weeks | Progress | Done / total | State |');
md.push('|---|---|---|---|---|');
for (const p of phases) {
  md.push(`| P${p.number} — ${p.title} | ${p.weeks || '—'} | \`${bar(p.percent, 12)}\` ${p.percent}% | ${p.counts.done} / ${p.total} | ${p.state} |`);
}
md.push('');
md.push('## Milestones');
md.push('');
md.push('| Milestone | Reached when | Status |');
md.push('|---|---|---|');
for (const m of milestones) md.push(`| ${m.id} ${m.name} | Phase ${m.phase} exit review | ${m.reached ? 'Reached' : 'Pending'} |`);
md.push('');
md.push('## Blocked');
md.push('');
const blocked = all.filter(i => i.status === 'blocked');
md.push(blocked.length ? blocked.map(i => `- **${i.id}** ${short(i.title)} — _${i.blockedReason}_`).join('\n') : '_None._');
md.push('');
md.push('## In progress');
md.push('');
const wip = all.filter(i => i.status === 'in-progress');
md.push(wip.length ? wip.map(i => `- **${i.id}** ${short(i.title)}`).join('\n') : '_None._');
md.push('');
md.push('## Open decisions due (gate at or before the next phase)');
md.push('');
md.push(decisionsDue.length
  ? ['| ID | Decision | Gate |', '|---|---|---|', ...decisionsDue.map(d => `| ${d.id} | ${short(d.question, 110)} | ${d.gate} |`)].join('\n')
  : '_None._');
md.push('');
const mdText = md.join('\n');

const json = JSON.stringify({
  overallPercent: overall, totalWeeks, totals, currentPhase: currentPhase?.number ?? null,
  phases: phases.map(({ items, ...p }) => ({ ...p, items })), milestones, decisionsDue,
}, null, 2) + '\n';

if (process.argv.includes('--check')) {
  const stale = !fs.existsSync(outMd) || fs.readFileSync(outMd, 'utf8') !== mdText
    || !fs.existsSync(outJson) || fs.readFileSync(outJson, 'utf8') !== json;
  if (stale) {
    console.error('docs/plan/PROGRESS.md is out of date. Run: node scripts/plan-progress.mjs');
    process.exit(1);
  }
  console.log('PROGRESS.md is up to date.');
} else {
  fs.writeFileSync(outMd, mdText);
  fs.writeFileSync(outJson, json);
  console.log(`Overall ${overall}% — ${totals.done}/${all.length} items done. Wrote docs/plan/PROGRESS.md and progress.json.`);
}
